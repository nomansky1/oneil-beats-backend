'use strict';

// Builds data/city-feeds.json from OpenPoliceData's source table: every
// police "calls for service" or "incidents" dataset on Socrata or ArcGIS
// that is still being updated. Re-run to pick up new cities:
//   git clone --depth 1 https://github.com/openpolicedata/opd-data /tmp/opd-data
//   node scripts/build-city-feeds.js /tmp/opd-data/opd_source_table.csv
// The source table is © openpolicedata, BSD 3-Clause (notice kept in the
// output). The datasets themselves belong to each agency.
const fs = require('fs');
const path = require('path');

const input = process.argv[2];
if (!input) { console.error('Usage: node scripts/build-city-feeds.js path/to/opd_source_table.csv'); process.exit(1); }

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows.filter((r) => r.length > 1);
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] || '').trim()])));
}

const toDate = (mdy) => { const [m, d, y] = mdy.split('/').map(Number); return y ? new Date(Date.UTC(y, m - 1, d)) : null; };
const thisYear = new Date().getUTCFullYear();
const freshAfter = new Date(Date.UTC(thisYear - 1, 9, 1)); // still updated within roughly the last year

const rows = parseCsv(fs.readFileSync(input, 'utf8'));
const feeds = rows
  .filter((r) => ['CALLS FOR SERVICE', 'INCIDENTS'].includes(r.TableType))
  .filter((r) => ['Socrata', 'ArcGIS'].includes(r.DataType))
  .filter((r) => !r.agency_field && !r.query) // single-agency tables only
  .filter((r) => r.date_field && !/year/i.test(r.date_field)) // needs a real timestamp
  .filter((r) => (r.Year === 'MULTIPLE' && toDate(r.coverage_end) >= freshAfter) || Number(r.Year) >= thisYear)
  .map((r) => ({
    id: `opd-${r.State}-${r.SourceName}-${r.TableType}`.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    state: r.State,
    agency: r.AgencyFull || r.Agency,
    city: r.Agency,
    type: r.TableType === 'CALLS FOR SERVICE' ? 'calls' : 'incidents',
    platform: r.DataType.toLowerCase(),
    url: r.DataType === 'Socrata' ? `https://${r.URL.replace(/^https?:\/\//, '').replace(/\/$/, '')}/resource/${r.dataset_id}.json` : r.URL,
    dateField: r.date_field,
    sourceUrl: r.source_url || '',
  }));

const out = {
  note: 'Generated by scripts/build-city-feeds.js from the OpenPoliceData source table (https://github.com/openpolicedata/opd-data). Copyright (c) 2022, openpolicedata. BSD 3-Clause License. Datasets belong to each agency.',
  generated: new Date().toISOString().slice(0, 10),
  feeds,
};
const file = path.join(__dirname, '..', 'data', 'city-feeds.json');
fs.writeFileSync(file, `${JSON.stringify(out, null, 1)}\n`);
console.log(`Wrote ${path.relative(process.cwd(), file)}: ${feeds.length} feeds in ${new Set(feeds.map((f) => `${f.city}, ${f.state}`)).size} places`);
